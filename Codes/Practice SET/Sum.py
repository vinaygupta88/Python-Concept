# Write a Program to input 2 number & print their sum, difference and product
num1=int(input("Enter First number: "))
num2=int(input("Enter Second number: "))


print("Sum : ", num1+num2)
print("Difference : ", num1-num2)
print("Product : ", num1*num2)
print("Remainder : ", num1%num2)
print("\nAverage of two float number: ",(float(num1)+float(num2))/2)
